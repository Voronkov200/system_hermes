    required this.affinity,
    required this.cleanStreak,
    required this.lifeLevel,
    required this.xp,
    required this.achievements,
    required this.energy,
    required this.mood,
    required this.fuelBalance,
    required this.assetsBalance,
    required this.keyFacts,
    required this.socialOutings,
    required this.daysSinceLastOuting,
    required this.freelanceSteps,
  });

  String toSystemPrompt() => buildAnastasiaSystemPrompt(
        affinity: affinity,
        cleanStreak: cleanStreak,
        lifeLevel: lifeLevel,
        xp: xp,
        achievements: achievements,
        energy: energy,
        mood: mood,
        fuelBalance: fuelBalance,
        assetsBalance: assetsBalance,
        keyFacts: keyFacts,
        socialOutings: socialOutings,
        daysSinceLastOuting: daysSinceLastOuting,
        freelanceSteps: freelanceSteps,
      );
}

