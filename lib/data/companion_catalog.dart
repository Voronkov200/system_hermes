/// Уровень отношений с Анастасией.
class CompanionRelationLevel {
  final int minAffinity;
  final String name;
  final String title;
  final String description;

  const CompanionRelationLevel({
    required this.minAffinity,
    required this.name,
    required this.title,
    required this.description,
  });
}

/// Уровни отношений (по возрастанию симпатии). Высокие уровни открывают
/// более персональные, внимательные реакции — не «контент» и не доступ
/// к чату (чат не блокируется никогда).
const List<CompanionRelationLevel> relationLevels = [
  CompanionRelationLevel(
    minAffinity: 0,
    name: 'Знакомая',
    title: 'знакомая',
    description: 'Присматривается к тебе. Доверие растёт от реальных действий.',
  ),
  CompanionRelationLevel(
    minAffinity: 20,
    name: 'Приятельница',
    title: 'приятельница',
    description: 'Уже замечает твои выходы из дома и рабочие дни.',
  ),
  CompanionRelationLevel(
    minAffinity: 40,
    name: 'Друг',
    title: 'друг',
    description: 'Подкалывает по-доброму и реально следит за твоим путём.',
  ),
  CompanionRelationLevel(
    minAffinity: 60,
    name: 'Близкий друг',
    title: 'близкий друг',
    description: 'Искренне радуется твоим реальным шагам — они важнее очков.',
  ),
  CompanionRelationLevel(
    minAffinity: 80,
    name: 'Свидетель',
    title: 'свидетель пути',
    description: 'Видит твой путь целиком и отмечает каждый реальный шаг.',
  ),
];

/// Уровень отношений для текущей симпатии.
CompanionRelationLevel levelForAffinity(double affinity) {
  CompanionRelationLevel best = relationLevels.first;
  for (final l in relationLevels) {
    if (affinity >= l.minAffinity) best = l;
  }
  return best;
}

/// Сколько осталось до следующего уровня (0.0-1.0).
double levelProgress(double affinity) {
  final current = levelForAffinity(affinity);
  final idx = relationLevels.indexOf(current);
  if (idx >= relationLevels.length - 1) return 1.0;
  final next = relationLevels[idx + 1];
  final span = next.minAffinity - current.minAffinity;
  if (span <= 0) return 1.0;
  return ((affinity - current.minAffinity) / span).clamp(0.0, 1.0);
}

/// Человекочитаемый текст про последний выход из дома (для промпта).
String daysSinceOutingText(int days) {
  if (days < 0) return 'ещё ни разу не выходил из дома';
  if (days == 0) return 'вышел из дома сегодня';
  if (days == 1) return 'последний выход из дома был вчера';
  return 'последний выход из дома был $days дн. назад';
}

