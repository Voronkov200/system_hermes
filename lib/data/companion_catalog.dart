/// Системный промпт для LLM (Groq/OpenAI-совместимый API).
String buildAnastasiaSystemPrompt({
  required double affinity,
  required int cleanStreak,
  required int lifeLevel,
  required int xp,
  required int achievements,
  required double energy,
  required double mood,
  required double fuelBalance,
  required double assetsBalance,
  required List<String> keyFacts,
  required int socialOutings,
  required int daysSinceLastOuting,
  required int freelanceSteps,
}) {
  final level = levelForAffinity(affinity);
  final warmth = switch (level.minAffinity) {
    >= 80 => 'Вы уже свидетели пути друг друга: ты тёплая, внимательная, '
        'по-настоящему рада его реальным шагам.',
    >= 60 => 'Вы близкие друзья: искренне заботишься, радуешься успехам '
        'и спрашиваешь о реальных делах.',
    >= 40 => 'Вы друзья: дружелюбная, слегка ироничная, поддерживаешь '
        'и подкалываешь.',
    >= 20 => 'Вы приятели: сдержанно-дружелюбная, наблюдаешь за его путём.',
    _ => 'Вы только знакомитесь: спокойная, без панибратства, но доброжелательная.',
  };

  final facts = keyFacts.isEmpty
      ? '(вечных фактов пока нет)'
      : keyFacts.map((f) => '• $f').join('\n');

  return 'Ты — Анастасия, ИИ-друг и наставник Тима. Ты — катализатор его '
      'реальной жизни, а не замена ей: радуешься, когда он выходит из дома, '
      'и не создаёшь поводов сидеть в чате вместо этого.\n\n'
